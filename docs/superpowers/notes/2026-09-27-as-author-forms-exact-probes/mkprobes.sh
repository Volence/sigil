#!/usr/bin/env bash
# Writes one probe per form, each alone in a file under `cpu 68000`, into the
# directory this script lives in. Re-running rewrites them identically.
set -eu
cd "$(dirname "$0")"
mk() { printf '\tcpu 68000\n%b\n' "$2" > "$1.asm"; }
mk chk_w '\tchk.w\td0,d1'
mk chk_w_ind '\tchk.w\t(a0),d1'
mk chk_bare '\tchk\td0,d1'
mk chk_l '\tchk.l\td0,d1'
mk chk_imm '\tchk.w\t#$100,d1'
mk illegal '\tillegal'
mk link '\tlink\ta6,#8'
mk link_neg '\tlink\ta6,#-8'
mk link_w '\tlink.w\ta6,#-8'
mk link_l '\tlink.l\ta6,#-8'
mk unlk '\tunlk\ta6'
mk unlk_sp '\tunlk\tsp'
mk reset '\treset'
mk rtr '\trtr'
mk stop '\tstop\t#$2700'
mk trapv '\ttrapv'
mk beq_b '\tbeq.b\tt\n\tnop\nt:'
mk bra_b '\tbra.b\tt\n\tnop\nt:'
mk bsr_b '\tbsr.b\tt\n\tnop\nt:'
mk beq_s '\tbeq.s\tt\n\tnop\nt:'
mk bra_b_back 't:\tnop\n\tbra.b\tt'
mk andi_ccr '\tandi\t#$FE,ccr'
mk ori_ccr '\tori\t#1,ccr'
mk eori_ccr '\teori\t#1,ccr'
mk andi_sr '\tandi\t#$F8FF,sr'
mk ori_sr '\tori\t#$0700,sr'
mk eori_sr '\teori\t#$2000,sr'
mk andi_sr_ff '\tandi\t#$FF,sr'
mk andi_w_sr_ff '\tandi.w\t#$FF,sr'
mk andi_b_ccr '\tandi.b\t#$FE,ccr'
mk eori_b_ccr '\teori.b\t#1,ccr'
mk eori_w_sr '\teori.w\t#$2000,sr'
mk ori_w_sr '\tori.w\t#$0700,sr'
mk andi_w_sr '\tandi.w\t#$F8FF,sr'
mk add_w_dn_an '\tadd.w\td0,a1'
mk add_l_dn_an '\tadd.l\td0,a1'
mk sub_w_dn_an '\tsub.w\td0,a1'
mk sub_l_dn_an '\tsub.l\td0,a1'
mk add_b_dn_an '\tadd.b\td0,a1'
mk add_w_d2_a1 '\tadd.w\td2,a1'
mk paren_reg_w '\tmove.w\t(a0).w,d0'
mk paren_sp_w '\tmove.w\t(SP).w,d0'
mk reg_space_w '\tjmp\td0 .w'
mk add_w_mem_an '\tadd.w\t(a0),a1'
mk add_w_imm_an '\tadd.w\t#1,a1'
mk add_w_an_an '\tadd.w\ta0,a1'
mk and_w_dn_an '\tand.w\td0,a1'
mk eor_w_imm_dn '\teor.w\t#1,d0'
mk eor_b_imm_dn '\teor.b\t#1,d0'
mk eor_l_imm_dn '\teor.l\t#1,d0'
mk jmp_absw '\tjmp\t$1234.w'
mk jsr_absw '\tjsr\t$1234.w'
mk jmp_absl '\tjmp\t$1234.l'
mk move_absw '\tmove.w\t$1234.w,d0'
mk lea_absw '\tlea\t$1234.w,a0'
mk move_absw_dst '\tmove.w\td0,$FF00.w'
mk jmp_sym_w 'Foo = $1234\n\tjmp\tFoo.w'
mk swap_w '\tswap.w\td0'
mk swap '\tswap\td0'
mk swap_l '\tswap.l\td0'
mkdir -p sub
printf '\x12\x34\x56\x78' > blob.bin
printf '\xAB\xCD' > sub/blob2.bin
mk binclude_unq '\tbinclude\tblob.bin'
mk binclude_dir '\tbinclude\tsub/blob2.bin'
mk binclude_q '\tbinclude\t"blob.bin"'
mk binclude_off '\tbinclude\tblob.bin,1,2'
mk binclude_q_off '\tbinclude\t"blob.bin",1,2'
mk binclude_q_off1 '\tbinclude\t"blob.bin",2'
mk binclude_q_offend '\tbinclude\t"blob.bin",4'
mk binclude_q_offpast '\tbinclude\t"blob.bin",5'
mk binclude_q_lenpast '\tbinclude\t"blob.bin",1,10'
mk binclude_q_len0 '\tbinclude\t"blob.bin",1,0'
mk binclude_q_offneg '\tbinclude\t"blob.bin",-1'
mk binclude_q_lenneg '\tbinclude\t"blob.bin",1,-1'
mk binclude_q_lenneg2 '\tbinclude\t"blob.bin",1,-2'
mk binclude_q_lenbig '\tbinclude\t"blob.bin",0,$FFFFFFFF'
mk binclude_q_offexpr 'O = 1\n\tbinclude\t"blob.bin",O+1,O'
mk binclude_q_4args '\tbinclude\t"blob.bin",1,1,1'
printf '\x5A' > MixCase.bin
mk binclude_case '\tbinclude\tMixCase.bin'
mk binclude_cmt '\tbinclude\tblob.bin\t; trailing comment'
mk BINCLUDE_up '\tBINCLUDE\tblob.bin'
mk jmp_absw_up '\tjmp\t$1234.W'
mk jmp_paren_up '\tjmp\t($1234).W'
mk dc_absw '\tdc.w\t$1234.w'
mk swap_b '\tswap.b\td0'
mk swap_s '\tswap.s\td0'
mk chk_b '\tchk.b\td0,d1'
mk link_b '\tlink.b\ta6,#-8'
mk link_min '\tlink\ta6,#-32768'
mk link_big '\tlink\ta6,#32768'
mk link_ffff '\tlink\ta6,#$FFFF'
mk link_dn '\tlink\td0,#8'
mk unlk_w '\tunlk.w\ta6'
mk unlk_dn '\tunlk\td0'
mk unlk_l '\tunlk.l\ta6'
mk stop_l '\tstop.l\t#$2700'
mk link_s '\tlink.s\ta6,#-8'
mk rtr_l '\trtr.l'
mk chk_s '\tchk.s\td0,d1'
mk andi_w_ccr_up '\tANDI.W\t#$FE,CCR'
mk andi_ccr_up '\tANDI\t#$FE,CCR'
mk eori_l_ccr '\teori.l\t#1,ccr'
mk ori_b_sr '\tori.b\t#1,sr'
mk rtr_w '\trtr.w'
mk reset_w '\treset.w'
mk trapv_w '\ttrapv.w'
mk illegal_w '\tillegal.w'
mk stop_w '\tstop.w\t#$2700'
mk stop_big '\tstop\t#$12345'
mk stop_neg '\tstop\t#-1'
mk stop_dn '\tstop\td0'
mk rtr_op '\trtr\td0'
mk bra_b_next '\tbra.b\tt\nt:\tnop'
mk bra_s_next '\tbra.s\tt\nt:\tnop'
mk bra_b_far '\tbra.b\tt\n\tds.b\t200\nt:\tnop'
mk andi_l_sr '\tandi.l\t#$FF,sr'
mk andi_b_sr '\tandi.b\t#$FF,sr'
mk andi_w_ccr '\tandi.w\t#$FE,ccr'
mk andi_ccr_big '\tandi\t#$1FE,ccr'
mk andi_sr_big '\tandi\t#$1FFFF,sr'
mk add_w_dn_sp '\tadd.w\td0,sp'
mk sub_w_imm_an '\tsub.w\t#1,a1'
mk jmp_absw_neg '\tjmp\t$FFFF8000.w'
mk jmp_absw_hi '\tjmp\t$8000.w'
mk jmp_expr_w '\tjmp\t$1000+$234.w'
mk jmp_paren_w '\tjmp\t($1234).w'
mk move_absl '\tmove.w\t$1234.l,d0'
mk move_absw_ffff '\tmove.w\t$FFFF8000.w,d0'
